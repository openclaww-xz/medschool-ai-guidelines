def main():
    missing, rows = [], []
    for d in ("us-med-schools", "health-systems"):
        for fn in sorted(os.listdir(os.path.join(BASE, "raw", d))):
            if not fn.endswith(".md"):
                continue
            rec = R.get(fn)
            if rec is None:
                missing.append(f"raw/{d}/{fn}")
                rows.append({"file": f"raw/{d}/{fn}"})
                continue
            row = {"file": f"raw/{d}/{fn}"}
            for c in COLS[1:]:
                row[c] = rec.get(c, "")
            rows.append(row)
    os.makedirs(os.path.join(BASE, "analysis"), exist_ok=True)
    out = os.path.join(BASE, "analysis", "clauses.csv")
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {out}: {len(rows)} rows")
    if missing:
        print("UNCURATED (blank rows emitted):")
        for m in missing: print("  " + m)
        sys.exit(2)

if __name__ == "__main__":
    main()
